CREATE TABLE rol (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo      VARCHAR(20) NOT NULL,
    nombre      VARCHAR(50) NOT NULL,
    descripcion TEXT,
    CONSTRAINT pk_rol PRIMARY KEY (id),
    CONSTRAINT uq_rol_codigo UNIQUE (codigo),
    CONSTRAINT ck_rol_codigo CHECK (codigo IN ('ADMINISTRADOR', 'PERSONAL_FEDER', 'PRODUCTOR', 'CLIENTE'))
);
COMMENT ON TABLE rol IS 'Catálogo cerrado de los cuatro roles de CU1.';

CREATE TABLE usuario (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    correo                    VARCHAR(120) NOT NULL,
    password_hash             VARCHAR(255),
    nombres                   VARCHAR(80)  NOT NULL,
    apellidos                 VARCHAR(80)  NOT NULL,
    ci                        INTEGER      NOT NULL,
    ci_complemento            VARCHAR(2),
    telefono                  INTEGER      NOT NULL,
    activo                    BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ultimo_acceso             TIMESTAMPTZ,
    fecha_aceptacion_terminos TIMESTAMPTZ,
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT ck_usuario_correo CHECK (correo ~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$'),
    -- «Cuenta invitada sin contraseña»: solo una cuenta inactiva puede no tener contraseña.
    CONSTRAINT ck_usuario_password_hash CHECK (activo = false OR password_hash IS NOT NULL),
    CONSTRAINT ck_usuario_nombres CHECK (nombres ~ '[[:alpha:]]' AND nombres !~ '[[:cntrl:]]'),
    CONSTRAINT ck_usuario_apellidos CHECK (apellidos ~ '[[:alpha:]]' AND apellidos !~ '[[:cntrl:]]'),
    CONSTRAINT ck_usuario_ci CHECK (ci BETWEEN 10000 AND 999999999),
    CONSTRAINT ck_usuario_ci_complemento CHECK (ci_complemento ~ '^[0-9A-Z]{2}$'),
    CONSTRAINT ck_usuario_telefono CHECK (telefono BETWEEN 20000000 AND 79999999)
);
COMMENT ON TABLE usuario IS 'Cuenta de acceso de una persona y sus datos de identificación.';

-- «Correo único»: sin distinguir mayúsculas.
CREATE UNIQUE INDEX uq_usuario_correo ON usuario (lower(correo));
-- «Una cuenta por persona»: la pareja (ci, ci_complemento) es única aunque el complemento sea nulo.
-- Se usa la forma de índice que el modelo prevé para versiones anteriores a PostgreSQL 15 (equivale a
-- UNIQUE NULLS NOT DISTINCT), para que el script no dependa de la versión del servidor.
CREATE UNIQUE INDEX uq_usuario_ci ON usuario (ci, COALESCE(ci_complemento, ''));

CREATE TABLE usuario_rol (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id        BIGINT      NOT NULL,
    rol_id            BIGINT      NOT NULL,
    asignado_por_id   BIGINT,
    revocado_por_id   BIGINT,
    estado            VARCHAR(10) NOT NULL,
    fecha_asignacion  TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_activacion  TIMESTAMPTZ,
    fecha_expiracion  TIMESTAMPTZ,
    fecha_revocacion  TIMESTAMPTZ,
    motivo            VARCHAR(255),
    motivo_revocacion VARCHAR(255),
    CONSTRAINT pk_usuario_rol PRIMARY KEY (id),
    CONSTRAINT fk_usuario_rol_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT fk_usuario_rol_rol FOREIGN KEY (rol_id) REFERENCES rol (id) ON DELETE RESTRICT,
    CONSTRAINT fk_usuario_rol_asignado_por FOREIGN KEY (asignado_por_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT fk_usuario_rol_revocado_por FOREIGN KEY (revocado_por_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT ck_usuario_rol_estado CHECK (estado IN ('PENDIENTE', 'VIGENTE', 'REVOCADA', 'ANULADA')),
    CONSTRAINT ck_usuario_rol_fecha_activacion CHECK (
        fecha_activacion >= fecha_asignacion
        AND (fecha_expiracion IS NULL OR fecha_activacion < fecha_expiracion)),
    CONSTRAINT ck_usuario_rol_fecha_expiracion CHECK (fecha_expiracion > fecha_asignacion),
    CONSTRAINT ck_usuario_rol_fecha_revocacion CHECK (
        fecha_revocacion >= fecha_asignacion
        AND fecha_revocacion >= COALESCE(fecha_activacion, fecha_asignacion)),
    -- «Ciclo de vida de la concesión»: datos coherentes con el estado.
    CONSTRAINT ck_usuario_rol_coherencia_estado CHECK (
        (estado = 'PENDIENTE' AND fecha_expiracion IS NOT NULL AND fecha_activacion IS NULL
            AND fecha_revocacion IS NULL AND revocado_por_id IS NULL AND motivo_revocacion IS NULL)
        OR (estado = 'VIGENTE' AND fecha_activacion IS NOT NULL
            AND fecha_revocacion IS NULL AND revocado_por_id IS NULL AND motivo_revocacion IS NULL)
        OR (estado = 'REVOCADA' AND fecha_activacion IS NOT NULL AND fecha_revocacion IS NOT NULL
            AND revocado_por_id IS NOT NULL AND motivo_revocacion IS NOT NULL)
        OR (estado = 'ANULADA' AND fecha_activacion IS NULL AND fecha_revocacion IS NOT NULL
            AND (revocado_por_id IS NULL OR motivo_revocacion IS NOT NULL))),
    -- «Concesión autorizada»: nadie se concede un rol a sí mismo.
    CONSTRAINT ck_usuario_rol_asignado_por_distinto CHECK (asignado_por_id IS NULL OR asignado_por_id <> usuario_id)
);
COMMENT ON TABLE usuario_rol IS 'Concesión de un rol a una cuenta, con su ciclo de vida e historial.';

-- «Concesión vigente única»: como máximo una concesión PENDIENTE o VIGENTE por (usuario, rol).
CREATE UNIQUE INDEX uq_usuario_rol_concesion_abierta ON usuario_rol (usuario_id, rol_id)
    WHERE estado IN ('PENDIENTE', 'VIGENTE');

CREATE TABLE bitacora (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id   BIGINT,
    fecha        TIMESTAMPTZ NOT NULL DEFAULT now(),
    accion       VARCHAR(20) NOT NULL,
    entidad      VARCHAR(60) NOT NULL,
    entidad_id   BIGINT,
    detalle      JSONB,
    direccion_ip INET,
    CONSTRAINT pk_bitacora PRIMARY KEY (id),
    CONSTRAINT fk_bitacora_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT ck_bitacora_accion CHECK (accion IN (
        'CREAR', 'MODIFICAR', 'ANULAR', 'ASIGNAR_ROL', 'REVOCAR_ROL', 'INICIO_SESION',
        'CAMBIO_PRECIO', 'APROBAR_SOLICITUD', 'RECHAZAR_SOLICITUD', 'INVITAR')),
    -- DETALLE_COMPRA «Recepción idempotente»: el registro de una recepción o cancelación de línea lleva
    -- siempre su clave de operación, la compra y la línea; la recepción indica además la cantidad aceptada
    -- (clave JSON cantidad_aceptada, numérica), que usa la regla «Precio de adquisición fijo».
    CONSTRAINT ck_bitacora_operacion_detalle_compra CHECK (
        entidad <> 'DETALLE_COMPRA'
        OR detalle IS NULL
        OR COALESCE(detalle ->> 'operacion', '') NOT IN ('RECEPCION', 'CANCELACION')
        OR (COALESCE(detalle ->> 'clave_operacion', '') <> ''
            AND COALESCE(detalle ->> 'compra_id', '') <> ''
            AND entidad_id IS NOT NULL
            AND (detalle ->> 'operacion' <> 'RECEPCION'
                 OR COALESCE(jsonb_typeof(detalle -> 'cantidad_aceptada'), '') = 'number')))
);
COMMENT ON TABLE bitacora IS 'Registro de auditoría de operaciones sensibles. Solo admite inserciones.';

-- DETALLE_COMPRA «Recepción idempotente»: una clave de operación no se registra dos veces...
CREATE UNIQUE INDEX uq_bitacora_clave_operacion ON bitacora ((detalle ->> 'clave_operacion'))
    WHERE entidad = 'DETALLE_COMPRA';
-- ...y una misma guía de entrega no se registra dos veces para la misma línea.
CREATE UNIQUE INDEX uq_bitacora_documento_entrega
    ON bitacora ((detalle ->> 'compra_id'), entidad_id, (detalle ->> 'documento_entrega'))
    WHERE entidad = 'DETALLE_COMPRA' AND detalle ->> 'operacion' = 'RECEPCION' AND detalle ? 'documento_entrega';

