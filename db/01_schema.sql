    BEFORE INSERT OR UPDATE ON reserva_stock
    FOR EACH ROW EXECUTE FUNCTION tgf_reserva_stock_integridad();

-- ---- MOVIMIENTO_INVENTARIO «Referencias según tipo», «Reingreso limitado» (lote),
--      «Ajuste positivo extraordinario» y cantidades enteras ---------------------------
CREATE OR REPLACE FUNCTION tgf_movimiento_inventario_validar()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_cantidad_reserva numeric(12,3);
    v_estado_reserva   varchar(20);
    v_lote_despacho    bigint;
    v_resolucion       varchar(15);
    v_pendiente        numeric;
    v_positivos        numeric;
    v_restituible      numeric;
BEGIN
    IF NEW.cantidad <> trunc(NEW.cantidad) THEN
        PERFORM feder_exigir_cantidad_entera(feder_producto_de_lote_feder(NEW.lote_feder_id), NEW.cantidad,
            'rg_movimiento_inventario_cantidad_entera', 'movimiento_inventario', 'cantidad');
    END IF;

    IF NEW.tipo IN ('SALIDA_VENTA', 'ENTRADA_RETORNO_ENTREGA') AND NEW.reserva_id IS NOT NULL THEN
        SELECT cantidad, estado INTO v_cantidad_reserva, v_estado_reserva
          FROM reserva_stock WHERE id = NEW.reserva_id;
        IF FOUND THEN
            IF NEW.tipo = 'SALIDA_VENTA' AND v_cantidad_reserva <> NEW.cantidad THEN
                PERFORM feder_rechazar('rg_movimiento_inventario_salida_venta_cantidad', 'movimiento_inventario',
                    'Una SALIDA_VENTA sale por la misma cantidad de su reserva.');
            END IF;
            IF NEW.tipo = 'SALIDA_VENTA' AND v_estado_reserva NOT IN ('ACTIVA', 'CONSUMIDA') THEN
                PERFORM feder_rechazar('rg_movimiento_inventario_salida_venta_reserva', 'movimiento_inventario',
                    'Una reserva LIBERADA o EXPIRADA no puede despacharse.');
            END IF;
            IF NEW.tipo = 'ENTRADA_RETORNO_ENTREGA' AND v_estado_reserva <> 'CONSUMIDA' THEN
                PERFORM feder_rechazar('rg_movimiento_inventario_retorno_reserva_consumida', 'movimiento_inventario',
                    'Un retorno de entrega exige una reserva CONSUMIDA.');
            END IF;
        END IF;
    ELSIF NEW.tipo IN ('ENTRADA_DEVOLUCION', 'AJUSTE_NEGATIVO') AND NEW.devolucion_id IS NOT NULL THEN
        SELECT m.lote_feder_id INTO v_lote_despacho
          FROM devolucion d
          JOIN movimiento_inventario m ON m.id = d.movimiento_inventario_id
         WHERE d.id = NEW.devolucion_id;
        IF FOUND AND v_lote_despacho <> NEW.lote_feder_id THEN
            PERFORM feder_rechazar('rg_movimiento_inventario_devolucion_mismo_lote', 'movimiento_inventario',
                'El reingreso de una devolución y su compensación se registran en el lote del despacho devuelto.');
        END IF;
    ELSIF NEW.tipo = 'SALIDA_REPOSICION' AND NEW.devolucion_id IS NOT NULL THEN
        SELECT resolucion INTO v_resolucion FROM devolucion WHERE id = NEW.devolucion_id;
        IF FOUND AND v_resolucion IS DISTINCT FROM 'REPOSICION' THEN
            PERFORM feder_rechazar('rg_movimiento_inventario_reposicion_resolucion', 'movimiento_inventario',
                'Una SALIDA_REPOSICION exige una devolución aprobada con resolución REPOSICION.');
        END IF;
    ELSIF NEW.tipo = 'AJUSTE_POSITIVO' THEN
        IF NOT EXISTS (SELECT 1
                         FROM usuario_rol ur
                         JOIN rol r ON r.id = ur.rol_id
                         JOIN usuario u ON u.id = ur.usuario_id
                        WHERE ur.usuario_id = NEW.usuario_id
                          AND r.codigo = 'ADMINISTRADOR'
                          AND ur.estado = 'VIGENTE'
                          AND u.activo) THEN
            PERFORM feder_rechazar('rg_movimiento_inventario_ajuste_positivo_autor', 'movimiento_inventario',
                'Un AJUSTE_POSITIVO solo lo registra un ADMINISTRADOR vigente.');
        END IF;
        -- El límite se evalúa con la fila del lote bloqueada.
        PERFORM 1 FROM lote_feder WHERE id = NEW.lote_feder_id FOR UPDATE;
        SELECT dc.cantidad_comprada - dc.cantidad_recibida - dc.cantidad_rechazada - dc.cantidad_cancelada
          INTO v_pendiente
          FROM lote_feder lf
          JOIN detalle_compra dc ON dc.id = lf.detalle_compra_id
         WHERE lf.id = NEW.lote_feder_id;
        IF v_pendiente > 0 THEN
            PERFORM feder_rechazar('rg_movimiento_inventario_ajuste_positivo_pendiente', 'movimiento_inventario',
                'La mercancía de una compra con cantidad pendiente se registra como recepción (ENTRADA_COMPRA), nunca como ajuste positivo.');
        END IF;
        SELECT COALESCE(sum(cantidad) FILTER (WHERE tipo = 'AJUSTE_POSITIVO'), 0),
               COALESCE(sum(cantidad) FILTER (WHERE (tipo = 'AJUSTE_NEGATIVO' AND devolucion_id IS NULL)
                                                 OR tipo IN ('BAJA_VENCIDO', 'BAJA_DANADO', 'BAJA_DEFECTUOSO')), 0)
          INTO v_positivos, v_restituible
          FROM movimiento_inventario
         WHERE lote_feder_id = NEW.lote_feder_id;
        IF v_positivos + NEW.cantidad > v_restituible THEN
            PERFORM feder_rechazar('rg_movimiento_inventario_ajuste_positivo_limite', 'movimiento_inventario',
                'Un AJUSTE_POSITIVO solo restituye unidades que salieron del lote por ajuste negativo o baja: la suma de ajustes positivos superaría ese límite.');
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_movimiento_inventario_validar
    BEFORE INSERT ON movimiento_inventario
    FOR EACH ROW EXECUTE FUNCTION tgf_movimiento_inventario_validar();

-- ---- DEVOLUCION «Pedido entregado», «Datos fijos desde la aprobación», «Atribución fija»,
--      «Rectificación controlada» (vínculo) y cantidades enteras ------------------------
CREATE OR REPLACE FUNCTION tgf_devolucion_integridad()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_tipo_despacho  varchar(25);
    v_lote_despacho  bigint;
    v_pedido_id      bigint;
    v_estado_pedido  varchar(30);
    v_estado_anulada varchar(15);
    v_producto_id    bigint;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF OLD.estado IN ('APROBADA', 'COMPLETADA', 'ANULADA')
           AND (NEW.movimiento_inventario_id IS DISTINCT FROM OLD.movimiento_inventario_id
                OR NEW.cantidad IS DISTINCT FROM OLD.cantidad
                OR NEW.cantidad_aprobada IS DISTINCT FROM OLD.cantidad_aprobada
                OR NEW.resolucion IS DISTINCT FROM OLD.resolucion) THEN
            PERFORM feder_rechazar('rg_devolucion_datos_fijos_desde_aprobacion', 'devolucion',
                'Desde la aprobación no se modifican el despacho devuelto, la cantidad, la cantidad aprobada ni la resolución; un error se corrige con la rectificación controlada.');
        END IF;
        IF OLD.estado IN ('APROBADA', 'COMPLETADA', 'ANULADA')
           AND NEW.importe_reembolsable IS DISTINCT FROM OLD.importe_reembolsable THEN
            PERFORM feder_rechazar('rg_devolucion_importe_fijo', 'devolucion',
                'El importe reembolsable se fija una sola vez, al aprobar la devolución, y no se modifica después.');
        END IF;
        IF NEW.devolucion_anulada_id IS DISTINCT FROM OLD.devolucion_anulada_id THEN
            PERFORM feder_rechazar('rg_devolucion_rectificacion_fija', 'devolucion',
                'El vínculo de rectificación se fija al registrar la devolución que rectifica y no cambia.');
        END IF;
    END IF;

    IF TG_OP = 'INSERT' OR NEW.movimiento_inventario_id IS DISTINCT FROM OLD.movimiento_inventario_id THEN
        SELECT tipo, lote_feder_id INTO v_tipo_despacho, v_lote_despacho
          FROM movimiento_inventario WHERE id = NEW.movimiento_inventario_id;
        IF FOUND THEN
            IF v_tipo_despacho NOT IN ('SALIDA_VENTA', 'SALIDA_REPOSICION') THEN
                PERFORM feder_rechazar('rg_devolucion_despacho_valido', 'devolucion',
                    'Una devolución se refiere a un despacho físico: un movimiento SALIDA_VENTA o SALIDA_REPOSICION.');
            END IF;
            v_pedido_id := feder_pedido_de_movimiento(NEW.movimiento_inventario_id);
            SELECT estado INTO v_estado_pedido FROM pedido WHERE id = v_pedido_id;
            IF v_estado_pedido IS DISTINCT FROM 'ENTREGADO' THEN
                PERFORM feder_rechazar('rg_devolucion_pedido_entregado', 'devolucion',
                    'Solo se solicita una devolución sobre un pedido ENTREGADO.');
            END IF;
        END IF;
    END IF;

    IF TG_OP = 'INSERT' AND NEW.devolucion_anulada_id IS NOT NULL THEN
        SELECT estado INTO v_estado_anulada FROM devolucion WHERE id = NEW.devolucion_anulada_id;
        IF FOUND AND v_estado_anulada <> 'ANULADA' THEN
            PERFORM feder_rechazar('rg_devolucion_rectifica_anulada', 'devolucion',
                'Solo una devolución ANULADA puede vincularse con la devolución que la rectifica.');
        END IF;
    END IF;

    IF NEW.cantidad <> trunc(NEW.cantidad)
       OR NEW.cantidad_aprobada <> trunc(NEW.cantidad_aprobada)
       OR NEW.cantidad_recibida <> trunc(NEW.cantidad_recibida)
       OR NEW.cantidad_apta <> trunc(NEW.cantidad_apta) THEN
        IF v_lote_despacho IS NULL THEN
            SELECT lote_feder_id INTO v_lote_despacho
              FROM movimiento_inventario WHERE id = NEW.movimiento_inventario_id;
        END IF;
        v_producto_id := feder_producto_de_lote_feder(v_lote_despacho);
        PERFORM feder_exigir_cantidad_entera(v_producto_id, NEW.cantidad,
            'rg_devolucion_cantidad_entera', 'devolucion', 'cantidad');
        PERFORM feder_exigir_cantidad_entera(v_producto_id, NEW.cantidad_aprobada,
            'rg_devolucion_cantidad_entera', 'devolucion', 'cantidad_aprobada');
        PERFORM feder_exigir_cantidad_entera(v_producto_id, NEW.cantidad_recibida,
            'rg_devolucion_cantidad_entera', 'devolucion', 'cantidad_recibida');
        PERFORM feder_exigir_cantidad_entera(v_producto_id, NEW.cantidad_apta,
            'rg_devolucion_cantidad_entera', 'devolucion', 'cantidad_apta');
    END IF;
    RETURN NEW;
END;
$$;

