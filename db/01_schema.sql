    CONSTRAINT ck_devolucion_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_devolucion_estado CHECK (estado IN ('SOLICITADA', 'APROBADA', 'RECHAZADA', 'COMPLETADA', 'ANULADA')),
    CONSTRAINT ck_devolucion_resolucion CHECK (resolucion IN ('REPOSICION', 'REEMBOLSO')),
