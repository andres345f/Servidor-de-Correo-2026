-- Rechaza la operación con SQLSTATE P0001 y deja el identificador de la regla en el campo «constraint».
CREATE OR REPLACE FUNCTION feder_rechazar(p_regla text, p_tabla text, p_mensaje text)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION USING
        ERRCODE = 'P0001',
        MESSAGE = p_mensaje,
        CONSTRAINT = p_regla,
        TABLE = p_tabla,
        SCHEMA = 'public';
END;
$$;

-- PRODUCTO «Cantidades enteras por pieza»: una cantidad con decimales solo se admite si el producto no
-- se vende por UNIDAD. Lee la unidad con bloqueo compartido para que no cambie durante la operación.
CREATE OR REPLACE FUNCTION feder_exigir_cantidad_entera(
    p_producto_id bigint, p_cantidad numeric, p_regla text, p_tabla text, p_columna text)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_unidad varchar(20);
BEGIN
    IF p_cantidad IS NULL OR p_cantidad = trunc(p_cantidad) OR p_producto_id IS NULL THEN
        RETURN;
    END IF;
    SELECT unidad_medida INTO v_unidad FROM producto WHERE id = p_producto_id FOR SHARE;
    IF v_unidad = 'UNIDAD' THEN
        PERFORM feder_rechazar(p_regla, p_tabla,
            format('La cantidad de %s.%s debe ser entera porque el producto se vende por UNIDAD (valor recibido: %s).',
                   p_tabla, p_columna, p_cantidad));
    END IF;
END;
$$;

-- Producto de un lote de origen (LOTE_PRODUCCION → PRODUCCION → PRODUCTO).
CREATE OR REPLACE FUNCTION feder_producto_de_lote_produccion(p_lote_produccion_id bigint)
RETURNS bigint
LANGUAGE sql
STABLE
AS $$
    SELECT pr.producto_id
      FROM lote_produccion lp
      JOIN produccion pr ON pr.id = lp.produccion_id
     WHERE lp.id = p_lote_produccion_id;
$$;

-- Producto de un lote de FEDER (LOTE_FEDER → DETALLE_COMPRA → LOTE_PRODUCCION → PRODUCCION → PRODUCTO).
CREATE OR REPLACE FUNCTION feder_producto_de_lote_feder(p_lote_feder_id bigint)
RETURNS bigint
LANGUAGE sql
STABLE
AS $$
    SELECT pr.producto_id
      FROM lote_feder lf
      JOIN detalle_compra dc ON dc.id = lf.detalle_compra_id
      JOIN lote_produccion lp ON lp.id = dc.lote_origen_id
      JOIN produccion pr ON pr.id = lp.produccion_id
     WHERE lf.id = p_lote_feder_id;
$$;

-- Pedido al que pertenece un despacho: el de la reserva de su SALIDA_VENTA o, en una SALIDA_REPOSICION,
-- el del despacho devuelto por la devolución que la generó (se sigue la cadena hasta la venta original).
CREATE OR REPLACE FUNCTION feder_pedido_de_movimiento(p_movimiento_id bigint)
RETURNS bigint
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_movimiento bigint := p_movimiento_id;
    v_reserva    bigint;
    v_devolucion bigint;
    v_pedido     bigint;
    v_pasos      integer := 0;
BEGIN
    WHILE v_movimiento IS NOT NULL AND v_pasos < 64 LOOP
        v_pasos := v_pasos + 1;
        SELECT reserva_id, devolucion_id INTO v_reserva, v_devolucion
          FROM movimiento_inventario WHERE id = v_movimiento;
        IF NOT FOUND THEN
            RETURN NULL;
        END IF;
        IF v_reserva IS NOT NULL THEN
            SELECT dp.pedido_id INTO v_pedido
              FROM reserva_stock rs
              JOIN detalle_pedido dp ON dp.id = rs.detalle_pedido_id
             WHERE rs.id = v_reserva;
            RETURN v_pedido;
        END IF;
        IF v_devolucion IS NULL THEN
            RETURN NULL;
        END IF;
        SELECT movimiento_inventario_id INTO v_movimiento FROM devolucion WHERE id = v_devolucion;
    END LOOP;
    RETURN NULL;
END;
$$;

