-- ---- DETALLE_PEDIDO «Precio y cantidad fijos», «Respaldo opcional» y cantidades enteras
CREATE OR REPLACE FUNCTION tgf_detalle_pedido_integridad()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_tipo_pedido        varchar(15);
    v_producto_respaldo  bigint;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        -- El pedido y el producto de la línea se fijan junto con los datos de la venta.
        IF NEW.cantidad IS DISTINCT FROM OLD.cantidad
           OR NEW.precio_unitario IS DISTINCT FROM OLD.precio_unitario
           OR NEW.subtotal IS DISTINCT FROM OLD.subtotal
           OR NEW.descripcion_venta IS DISTINCT FROM OLD.descripcion_venta
           OR NEW.pedido_id IS DISTINCT FROM OLD.pedido_id
           OR NEW.producto_id IS DISTINCT FROM OLD.producto_id THEN
            PERFORM feder_rechazar('rg_detalle_pedido_datos_fijos', 'detalle_pedido',
                'Desde la confirmación del pedido no se modifican el producto, la cantidad, el precio, el subtotal ni la descripción de una línea.');
        END IF;
    ELSE
        PERFORM feder_exigir_cantidad_entera(NEW.producto_id, NEW.cantidad,
            'rg_detalle_pedido_cantidad_entera', 'detalle_pedido', 'cantidad');
    END IF;
    IF NEW.produccion_id IS NOT NULL
       AND (TG_OP = 'INSERT' OR NEW.produccion_id IS DISTINCT FROM OLD.produccion_id) THEN
        SELECT tipo INTO v_tipo_pedido FROM pedido WHERE id = NEW.pedido_id;
        IF v_tipo_pedido IS NOT NULL AND v_tipo_pedido <> 'ENCARGO' THEN
            PERFORM feder_rechazar('rg_detalle_pedido_respaldo_solo_encargo', 'detalle_pedido',
                'Solo una línea de ENCARGO puede referenciar una producción de respaldo.');
        END IF;
        SELECT producto_id INTO v_producto_respaldo FROM produccion WHERE id = NEW.produccion_id;
        IF v_producto_respaldo IS NOT NULL AND v_producto_respaldo <> NEW.producto_id THEN
            PERFORM feder_rechazar('rg_detalle_pedido_respaldo_mismo_producto', 'detalle_pedido',
                'La producción de respaldo debe ser del mismo producto que la línea del encargo.');
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

