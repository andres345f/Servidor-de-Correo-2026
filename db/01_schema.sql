-- =====================================================================================
-- 5. INFRAESTRUCTURA DEL PROCESADOR DE CORREO (no forma parte del modelo UML)
--
--    Tablas técnicas del canal de correo: control de mensajes entrantes ya procesados (idempotencia
--    por buzón y UIDL), cola de respuestas salientes con reintentos y códigos de confirmación de un
--    solo uso. No representan conceptos del dominio ni participan en las reglas R001–R102.
-- =====================================================================================

CREATE TABLE mensaje_correo (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    buzon        VARCHAR(120) NOT NULL,
    uidl         VARCHAR(100) NOT NULL,
    message_id   VARCHAR(255),
    remitente    VARCHAR(254) NOT NULL,
    asunto       VARCHAR(500),
    comando      VARCHAR(20),
    estado       VARCHAR(20)  NOT NULL,
    resultado    VARCHAR(20),
    detalle      VARCHAR(500),
    recibido_en  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    procesado_en TIMESTAMPTZ,
    CONSTRAINT pk_mensaje_correo PRIMARY KEY (id),
    -- Un mensaje del buzón se procesa una sola vez.
    CONSTRAINT uq_mensaje_correo_buzon_uidl UNIQUE (buzon, uidl),
    CONSTRAINT ck_mensaje_correo_estado CHECK (estado IN ('PROCESANDO', 'PROCESADO', 'IGNORADO', 'ERROR')),
    CONSTRAINT ck_mensaje_correo_resultado CHECK (resultado IN ('EXITO', 'ERROR', 'CONFIRMACION'))
);
COMMENT ON TABLE mensaje_correo IS 'Técnica: mensajes entrantes leídos del buzón y su resultado de procesamiento.';

CREATE INDEX ix_mensaje_correo_remitente_recibido ON mensaje_correo (remitente, recibido_en);

CREATE TABLE correo_saliente (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    mensaje_correo_id BIGINT,
    destinatario      VARCHAR(254) NOT NULL,
    asunto            VARCHAR(300) NOT NULL,
    cuerpo_texto      TEXT         NOT NULL,
    cuerpo_html       TEXT,
    message_id        VARCHAR(255) NOT NULL,
    en_respuesta_a    VARCHAR(255),
    estado            VARCHAR(15)  NOT NULL DEFAULT 'PENDIENTE',
    intentos          INTEGER      NOT NULL DEFAULT 0,
    ultimo_error      VARCHAR(500),
    creado_en         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    proximo_intento   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    enviado_en        TIMESTAMPTZ,
    -- Archivo adjunto opcional (reportes PDF o Excel de CU8), guardado con la respuesta para
    -- que un reintento de envío no tenga que volver a generarlo.
    adjunto_nombre    VARCHAR(100),
    adjunto_tipo      VARCHAR(100),
    adjunto_contenido BYTEA,
    -- Notificación del canal CORREO que este envío entrega (R045): al aceptarlo el servidor SMTP pasa a
    -- ENVIADA con su fecha_envio; si el intento falla, a FALLIDA (se reintenta con el mismo correo).
    notificacion_id   BIGINT,
    CONSTRAINT pk_correo_saliente PRIMARY KEY (id),
    CONSTRAINT fk_correo_saliente_mensaje_correo FOREIGN KEY (mensaje_correo_id)
        REFERENCES mensaje_correo (id) ON DELETE RESTRICT,
    CONSTRAINT fk_correo_saliente_notificacion FOREIGN KEY (notificacion_id)
        REFERENCES notificacion (id) ON DELETE RESTRICT,
    CONSTRAINT uq_correo_saliente_message_id UNIQUE (message_id),
    CONSTRAINT ck_correo_saliente_estado CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'FALLIDO')),
    CONSTRAINT ck_correo_saliente_adjunto CHECK (
        (adjunto_nombre IS NULL AND adjunto_tipo IS NULL AND adjunto_contenido IS NULL)
        OR (adjunto_nombre IS NOT NULL AND adjunto_tipo IS NOT NULL AND adjunto_contenido IS NOT NULL))
);
COMMENT ON TABLE correo_saliente IS 'Técnica: cola de correos de respuesta con control de reintentos.';

CREATE INDEX ix_correo_saliente_mensaje_correo ON correo_saliente (mensaje_correo_id);
CREATE INDEX ix_correo_saliente_notificacion ON correo_saliente (notificacion_id);
-- Cola de envío: solo los correos pendientes, por fecha del próximo intento.
CREATE INDEX ix_correo_saliente_pendiente ON correo_saliente (proximo_intento) WHERE estado = 'PENDIENTE';

CREATE TABLE confirmacion_operacion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- SHA-256 en hexadecimal del código de un solo uso; el código nunca se guarda en claro.
    codigo_hash       CHAR(64)     NOT NULL,
    -- Dirección (en minúsculas) a la que se envió el código.
    correo            VARCHAR(254) NOT NULL,
    -- Nulo cuando todavía no existe la cuenta (verificación del correo en el registro público).
    usuario_id        BIGINT,
    comando           VARCHAR(20)  NOT NULL,
    parametros        JSONB        NOT NULL,
    creada_en         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expira_en         TIMESTAMPTZ  NOT NULL,
    usada_en          TIMESTAMPTZ,
    intentos_fallidos INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT pk_confirmacion_operacion PRIMARY KEY (id),
    CONSTRAINT fk_confirmacion_operacion_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT uq_confirmacion_operacion_codigo_hash UNIQUE (codigo_hash),
    CONSTRAINT ck_confirmacion_operacion_vigencia CHECK (expira_en > creada_en)
);
COMMENT ON TABLE confirmacion_operacion IS 'Técnica: códigos de confirmación de un solo uso (solo su hash) para operaciones por correo.';

CREATE INDEX ix_confirmacion_operacion_correo_creada ON confirmacion_operacion (correo, creada_en);
CREATE INDEX ix_confirmacion_operacion_usuario ON confirmacion_operacion (usuario_id);

