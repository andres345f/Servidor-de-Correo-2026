    BEFORE INSERT OR UPDATE ON detalle_pedido
    FOR EACH ROW EXECUTE FUNCTION tgf_detalle_pedido_integridad();

-- ---- RESERVA_STOCK «Mismo producto», datos fijos y cantidades enteras ------------------
CREATE OR REPLACE FUNCTION tgf_reserva_stock_integridad()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_producto_lote  bigint;
    v_producto_linea bigint;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        -- Solo cambian el estado y sus fechas; una reasignación crea otra reserva.
        IF NEW.lote_feder_id IS DISTINCT FROM OLD.lote_feder_id
           OR NEW.detalle_pedido_id IS DISTINCT FROM OLD.detalle_pedido_id
           OR NEW.cantidad IS DISTINCT FROM OLD.cantidad THEN
            PERFORM feder_rechazar('rg_reserva_stock_datos_fijos', 'reserva_stock',
                'El lote, la línea de pedido y la cantidad de una reserva no cambian; una reasignación crea otra reserva.');
        END IF;
        RETURN NEW;
    END IF;
    v_producto_lote := feder_producto_de_lote_feder(NEW.lote_feder_id);
    SELECT producto_id INTO v_producto_linea FROM detalle_pedido WHERE id = NEW.detalle_pedido_id;
    IF v_producto_lote IS NOT NULL AND v_producto_linea IS NOT NULL AND v_producto_lote <> v_producto_linea THEN
        PERFORM feder_rechazar('rg_reserva_stock_mismo_producto', 'reserva_stock',
            'El producto del lote reservado debe ser el producto de la línea de pedido.');
    END IF;
    PERFORM feder_exigir_cantidad_entera(v_producto_lote, NEW.cantidad,
        'rg_reserva_stock_cantidad_entera', 'reserva_stock', 'cantidad');
    RETURN NEW;
END;
$$;

