CREATE TABLE comunidad_agricola (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR(120) NOT NULL,
    municipio    VARCHAR(80)  NOT NULL,
    departamento VARCHAR(40)  NOT NULL DEFAULT 'Santa Cruz',
    descripcion  TEXT,
    activa       BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_comunidad_agricola PRIMARY KEY (id),
    CONSTRAINT uq_comunidad_agricola_nombre_municipio UNIQUE (nombre, municipio)
);
COMMENT ON TABLE comunidad_agricola IS 'Comunidad agrícola que agrupa a productores; se da de baja de forma lógica.';

CREATE TABLE categoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(60) NOT NULL,
    descripcion TEXT,
    activa      BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_categoria PRIMARY KEY (id),
    CONSTRAINT uq_categoria_nombre UNIQUE (nombre)
);
COMMENT ON TABLE categoria IS 'Categoría del catálogo unificado, administrada por el personal de FEDER.';

CREATE TABLE producto (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    categoria_id    BIGINT        NOT NULL,
    codigo          VARCHAR(30)   NOT NULL,
    nombre          VARCHAR(120)  NOT NULL,
    descripcion     TEXT,
    presentacion    VARCHAR(60)   NOT NULL,
    unidad_medida   VARCHAR(20)   NOT NULL,
    precio_venta    NUMERIC(12,2) NOT NULL,
    stock_minimo    NUMERIC(12,3) NOT NULL DEFAULT 0,
    imagen_url      VARCHAR(255),
    permite_encargo BOOLEAN       NOT NULL DEFAULT FALSE,
    activo          BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_producto PRIMARY KEY (id),
    CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id) ON DELETE RESTRICT,
    CONSTRAINT uq_producto_codigo UNIQUE (codigo),
    CONSTRAINT ck_producto_unidad_medida CHECK (unidad_medida IN ('KILOGRAMO', 'LIBRA', 'ARROBA', 'LITRO', 'UNIDAD')),
    CONSTRAINT ck_producto_precio_venta CHECK (precio_venta > 0),
    CONSTRAINT ck_producto_stock_minimo CHECK (stock_minimo >= 0),
    -- «Cantidades enteras por pieza»: el umbral de un producto por UNIDAD es entero.
    CONSTRAINT ck_producto_stock_minimo_entero CHECK (unidad_medida <> 'UNIDAD' OR stock_minimo = trunc(stock_minimo))
);
COMMENT ON TABLE producto IS 'Artículo del catálogo que FEDER vende. Su stock se deriva de los LOTE_FEDER.';

CREATE TABLE productor (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id            BIGINT       NOT NULL,
    comunidad_agricola_id BIGINT       NOT NULL,
    codigo_productor      VARCHAR(20),
    estado_solicitud      VARCHAR(10)  NOT NULL DEFAULT 'PENDIENTE',
    fecha_solicitud       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_revision        TIMESTAMPTZ,
    motivo_rechazo        VARCHAR(255),
    ubicacion_actividad   VARCHAR(200) NOT NULL,
    fecha_afiliacion      DATE,
    activo                BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_productor PRIMARY KEY (id),
    CONSTRAINT fk_productor_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT fk_productor_comunidad_agricola FOREIGN KEY (comunidad_agricola_id)
        REFERENCES comunidad_agricola (id) ON DELETE RESTRICT,
    -- Una cuenta tiene como máximo un perfil de productor.
    CONSTRAINT uq_productor_usuario UNIQUE (usuario_id),
    CONSTRAINT uq_productor_codigo_productor UNIQUE (codigo_productor),
    CONSTRAINT ck_productor_estado_solicitud CHECK (estado_solicitud IN ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
    CONSTRAINT ck_productor_fecha_revision CHECK (fecha_revision >= fecha_solicitud),
    CONSTRAINT ck_productor_ubicacion_actividad CHECK (
        ubicacion_actividad ~ '[[:alnum:]]' AND ubicacion_actividad !~ '[[:cntrl:]]'),
    -- «Revisión independiente»: datos coherentes con el estado de la solicitud.
    CONSTRAINT ck_productor_coherencia_solicitud CHECK (
        (estado_solicitud = 'PENDIENTE' AND fecha_revision IS NULL AND motivo_rechazo IS NULL)
        OR (estado_solicitud = 'APROBADA' AND fecha_revision IS NOT NULL AND codigo_productor IS NOT NULL
            AND fecha_afiliacion IS NOT NULL AND motivo_rechazo IS NULL)
        OR (estado_solicitud = 'RECHAZADA' AND fecha_revision IS NOT NULL AND motivo_rechazo IS NOT NULL)),
    -- «Perfil con rol vigente» (parte comprobable en la fila): solo un perfil aprobado puede estar activo.
    CONSTRAINT ck_productor_activo_aprobado CHECK (activo = false OR estado_solicitud = 'APROBADA')
);
COMMENT ON TABLE productor IS 'Perfil de negocio del productor y su solicitud de alta.';

CREATE TABLE produccion (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    productor_id                  BIGINT       NOT NULL,
    producto_id                   BIGINT       NOT NULL,
    comunidad_origen_id           BIGINT       NOT NULL,
    codigo                        VARCHAR(30)  NOT NULL,
    fecha_inicio                  DATE,
    fecha_disponibilidad_estimada DATE,
    cantidad_estimada             NUMERIC(12,3),
    ubicacion_produccion          VARCHAR(200),
    estado                        VARCHAR(20)  NOT NULL,
    observacion                   TEXT,
    nombre_comunidad_origen       VARCHAR(120) NOT NULL,
    municipio_origen              VARCHAR(80)  NOT NULL,
    departamento_origen           VARCHAR(40)  NOT NULL,
    CONSTRAINT pk_produccion PRIMARY KEY (id),
    CONSTRAINT fk_produccion_productor FOREIGN KEY (productor_id) REFERENCES productor (id) ON DELETE RESTRICT,
    CONSTRAINT fk_produccion_producto FOREIGN KEY (producto_id) REFERENCES producto (id) ON DELETE RESTRICT,
    CONSTRAINT fk_produccion_comunidad_origen FOREIGN KEY (comunidad_origen_id)
        REFERENCES comunidad_agricola (id) ON DELETE RESTRICT,
    CONSTRAINT uq_produccion_codigo UNIQUE (codigo),
    CONSTRAINT ck_produccion_estado CHECK (estado IN ('PLANIFICADA', 'EN_CURSO', 'TERMINADA', 'CANCELADA')),
    CONSTRAINT ck_produccion_fecha_inicio CHECK (fecha_inicio IS NOT NULL OR estado = 'TERMINADA'),
    CONSTRAINT ck_produccion_fecha_disponibilidad_estimada CHECK (fecha_disponibilidad_estimada >= fecha_inicio),
    CONSTRAINT ck_produccion_cantidad_estimada CHECK (cantidad_estimada > 0),
    CONSTRAINT ck_produccion_ubicacion_produccion CHECK (
        ubicacion_produccion IS NULL
        OR (ubicacion_produccion ~ '[[:alnum:]]' AND ubicacion_produccion !~ '[[:cntrl:]]'))
);
COMMENT ON TABLE produccion IS 'Producción de un producto terminado por un productor, con su procedencia histórica.';

CREATE TABLE lote_produccion (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    produccion_id      BIGINT        NOT NULL,
    codigo_lote        VARCHAR(30)   NOT NULL,
    fecha_elaboracion  DATE,
    fecha_vencimiento  DATE,
    cantidad_producida NUMERIC(12,3) NOT NULL,
    cantidad_ofrecida  NUMERIC(12,3) NOT NULL,
    precio_ofrecido    NUMERIC(12,2),
    estado             VARCHAR(20)   NOT NULL,
    CONSTRAINT pk_lote_produccion PRIMARY KEY (id),
    CONSTRAINT fk_lote_produccion_produccion FOREIGN KEY (produccion_id) REFERENCES produccion (id) ON DELETE RESTRICT,
    CONSTRAINT uq_lote_produccion_codigo_lote UNIQUE (codigo_lote),
    CONSTRAINT ck_lote_produccion_estado CHECK (estado IN ('DISPONIBLE', 'AGOTADO', 'RETIRADO')),
    CONSTRAINT ck_lote_produccion_fecha_vencimiento CHECK (fecha_vencimiento >= fecha_elaboracion),
    CONSTRAINT ck_lote_produccion_vencimiento_con_elaboracion CHECK (
        fecha_vencimiento IS NULL OR fecha_elaboracion IS NOT NULL),
    CONSTRAINT ck_lote_produccion_cantidad_producida CHECK (cantidad_producida > 0),
    CONSTRAINT ck_lote_produccion_cantidad_ofrecida CHECK (
        cantidad_ofrecida >= 0 AND cantidad_ofrecida <= cantidad_producida),
    CONSTRAINT ck_lote_produccion_precio_ofrecido CHECK (precio_ofrecido >= 0)
);
COMMENT ON TABLE lote_produccion IS 'Lote de producto terminado de origen, todavía en poder del productor.';

