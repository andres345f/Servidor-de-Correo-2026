-- ---- PRODUCTO «Unidad comercial inmutable» -------------------------------------------
CREATE OR REPLACE FUNCTION tgf_producto_unidad_inmutable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.unidad_medida IS DISTINCT FROM OLD.unidad_medida OR NEW.presentacion IS DISTINCT FROM OLD.presentacion THEN
        -- Las compras y los movimientos de un producto existen siempre a través de una producción.
        IF EXISTS (SELECT 1 FROM produccion WHERE producto_id = OLD.id)
           OR EXISTS (SELECT 1 FROM detalle_pedido WHERE producto_id = OLD.id) THEN
            PERFORM feder_rechazar('rg_producto_unidad_inmutable', 'producto',
                'La unidad de medida y la presentación no cambian si el producto ya tiene producciones, compras, pedidos o movimientos; registre un producto nuevo con otro código.');
        END IF;
        IF NEW.unidad_medida = 'UNIDAD'
           AND EXISTS (SELECT 1 FROM item_carrito WHERE producto_id = OLD.id AND cantidad <> trunc(cantidad)) THEN
            PERFORM feder_rechazar('rg_producto_unidad_inmutable', 'producto',
                'El producto no puede pasar a venderse por UNIDAD mientras haya carritos con cantidades decimales de este producto.');
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_producto_unidad_inmutable
    BEFORE UPDATE OF unidad_medida, presentacion ON producto
    FOR EACH ROW EXECUTE FUNCTION tgf_producto_unidad_inmutable();

-- ---- PRODUCCION «Integridad de la producción» y «Procedencia histórica» ---------------
CREATE OR REPLACE FUNCTION tgf_produccion_integridad()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF OLD.fecha_inicio IS NOT NULL AND NEW.fecha_inicio IS NULL THEN
            PERFORM feder_rechazar('rg_produccion_fecha_inicio_no_vacia', 'produccion',
                'La fecha de inicio de una producción, una vez registrada, no vuelve a quedar vacía.');
        END IF;
        IF NEW.comunidad_origen_id IS DISTINCT FROM OLD.comunidad_origen_id THEN
            PERFORM feder_rechazar('rg_produccion_comunidad_origen_fija', 'produccion',
                'La comunidad de origen de una producción se fija al crearla y no se modifica.');
        END IF;
        IF (NEW.productor_id IS DISTINCT FROM OLD.productor_id OR NEW.producto_id IS DISTINCT FROM OLD.producto_id)
           AND (EXISTS (SELECT 1 FROM lote_produccion WHERE produccion_id = OLD.id)
                OR EXISTS (SELECT 1 FROM detalle_pedido WHERE produccion_id = OLD.id)) THEN
            PERFORM feder_rechazar('rg_produccion_productor_producto_fijos', 'produccion',
                'El productor y el producto de una producción no cambian desde que tiene lotes o respalda algún encargo.');
        END IF;
        IF NEW.fecha_inicio IS NOT NULL AND NEW.fecha_inicio IS DISTINCT FROM OLD.fecha_inicio
           AND EXISTS (SELECT 1 FROM lote_produccion
                        WHERE produccion_id = OLD.id AND fecha_elaboracion < NEW.fecha_inicio) THEN
            PERFORM feder_rechazar('rg_lote_produccion_elaboracion_desde_inicio', 'produccion',
                'La fecha de inicio de la producción no puede ser posterior a la fecha de elaboración de sus lotes.');
        END IF;
    END IF;
    PERFORM feder_exigir_cantidad_entera(NEW.producto_id, NEW.cantidad_estimada,
        'rg_produccion_cantidad_entera', 'produccion', 'cantidad_estimada');
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_produccion_integridad
    BEFORE INSERT OR UPDATE ON produccion
    FOR EACH ROW EXECUTE FUNCTION tgf_produccion_integridad();

-- ---- LOTE_PRODUCCION «Registro e integridad del lote de origen» -----------------------
CREATE OR REPLACE FUNCTION tgf_lote_produccion_integridad()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_fecha_inicio date;
    v_producto_id  bigint;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.produccion_id IS DISTINCT FROM OLD.produccion_id THEN
            PERFORM feder_rechazar('rg_lote_produccion_produccion_fija', 'lote_produccion',
                'Un lote de origen pertenece a una única producción y nunca se reasigna a otra.');
        END IF;
        IF NEW.codigo_lote IS DISTINCT FROM OLD.codigo_lote THEN
            PERFORM feder_rechazar('rg_lote_produccion_codigo_fijo', 'lote_produccion',
                'El código de trazabilidad de un lote de origen no cambia.');
        END IF;
    END IF;
    IF NEW.fecha_elaboracion IS NOT NULL
       AND (TG_OP = 'INSERT' OR NEW.fecha_elaboracion IS DISTINCT FROM OLD.fecha_elaboracion) THEN
        -- Bloqueo compartido: una edición simultánea de la fecha de inicio espera a esta operación.
        SELECT fecha_inicio INTO v_fecha_inicio FROM produccion WHERE id = NEW.produccion_id FOR SHARE;
        IF v_fecha_inicio IS NOT NULL AND NEW.fecha_elaboracion < v_fecha_inicio THEN
            PERFORM feder_rechazar('rg_lote_produccion_elaboracion_desde_inicio', 'lote_produccion',
                'La fecha de elaboración del lote no puede ser anterior a la fecha de inicio de su producción.');
        END IF;
    END IF;
    IF NEW.cantidad_producida <> trunc(NEW.cantidad_producida)
       OR NEW.cantidad_ofrecida <> trunc(NEW.cantidad_ofrecida) THEN
        SELECT producto_id INTO v_producto_id FROM produccion WHERE id = NEW.produccion_id;
        PERFORM feder_exigir_cantidad_entera(v_producto_id, NEW.cantidad_producida,
            'rg_lote_produccion_cantidad_entera', 'lote_produccion', 'cantidad_producida');
        PERFORM feder_exigir_cantidad_entera(v_producto_id, NEW.cantidad_ofrecida,
            'rg_lote_produccion_cantidad_entera', 'lote_produccion', 'cantidad_ofrecida');
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_lote_produccion_integridad
    BEFORE INSERT OR UPDATE ON lote_produccion
    FOR EACH ROW EXECUTE FUNCTION tgf_lote_produccion_integridad();

