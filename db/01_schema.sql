CREATE TABLE historial_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    pedido_id       BIGINT      NOT NULL,
    usuario_id      BIGINT,
    estado_anterior VARCHAR(30),
    estado_nuevo    VARCHAR(30) NOT NULL,
    fecha           TIMESTAMPTZ NOT NULL DEFAULT now(),
    comentario      VARCHAR(255),
    CONSTRAINT pk_historial_pedido PRIMARY KEY (id),
    CONSTRAINT fk_historial_pedido_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE RESTRICT,
    CONSTRAINT fk_historial_pedido_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT ck_historial_pedido_estado_anterior CHECK (estado_anterior IN (
        'PENDIENTE', 'ESPERANDO_ABASTECIMIENTO', 'CONFIRMADO', 'EN_PREPARACION', 'DESPACHADO', 'ENTREGADO', 'CANCELADO')),
    CONSTRAINT ck_historial_pedido_estado_nuevo CHECK (estado_nuevo IN (
        'PENDIENTE', 'ESPERANDO_ABASTECIMIENTO', 'CONFIRMADO', 'EN_PREPARACION', 'DESPACHADO', 'ENTREGADO', 'CANCELADO')),
    -- «Transición válida»: pares permitidos por EstadoPedido (unión de INMEDIATO y ENCARGO).
    -- Que el par corresponda al tipo del pedido y que el último registro coincida con PEDIDO.estado
    -- lo garantiza la capa de negocio.
    -- Se escribe con CASE para que un estado anterior nulo no deje el resultado indeterminado.
    CONSTRAINT ck_historial_pedido_transicion CHECK (
        CASE
            WHEN estado_anterior IS NULL THEN estado_nuevo = 'PENDIENTE'
            WHEN estado_anterior = 'PENDIENTE' THEN estado_nuevo IN ('CONFIRMADO', 'ESPERANDO_ABASTECIMIENTO', 'CANCELADO')
            WHEN estado_anterior = 'ESPERANDO_ABASTECIMIENTO' THEN estado_nuevo IN ('CONFIRMADO', 'CANCELADO')
            WHEN estado_anterior = 'CONFIRMADO' THEN estado_nuevo IN ('EN_PREPARACION', 'CANCELADO')
            WHEN estado_anterior = 'EN_PREPARACION' THEN estado_nuevo IN ('DESPACHADO', 'CANCELADO')
            WHEN estado_anterior = 'DESPACHADO' THEN estado_nuevo IN ('ENTREGADO', 'CANCELADO')
            ELSE false
        END),
    -- «Responsable de la cancelación»: toda cancelación lleva comentario.
    CONSTRAINT ck_historial_pedido_comentario_cancelacion CHECK (
        estado_nuevo <> 'CANCELADO' OR (comentario IS NOT NULL AND btrim(comentario) <> ''))
);
COMMENT ON TABLE historial_pedido IS 'Línea de tiempo de los cambios de estado de un pedido.';

