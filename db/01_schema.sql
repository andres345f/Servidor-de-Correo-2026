    -- Decisión: la resolución es obligatoria desde APROBADA y la cantidad aprobada existe solo desde entonces.
    CONSTRAINT ck_devolucion_resolucion_desde_aprobada CHECK (
        estado NOT IN ('APROBADA', 'COMPLETADA', 'ANULADA') OR resolucion IS NOT NULL),
    CONSTRAINT ck_devolucion_aprobada_desde_aprobada CHECK (
        (estado IN ('APROBADA', 'COMPLETADA', 'ANULADA')) = (cantidad_aprobada IS NOT NULL)),
    -- «Resolución excluyente»: importe no nulo solo desde APROBADA con resolución REEMBOLSO.
    CONSTRAINT ck_devolucion_importe_segun_resolucion CHECK (
        (importe_reembolsable IS NOT NULL)
