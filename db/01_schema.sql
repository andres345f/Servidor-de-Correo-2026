RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_productor_lote   bigint;
    v_producto_id      bigint;
    v_productor_compra bigint;
    v_fecha_pago       timestamptz;
BEGIN
    IF TG_OP = 'INSERT' THEN
        SELECT pr.productor_id INTO v_productor_lote
          FROM lote_produccion lp
          JOIN produccion pr ON pr.id = lp.produccion_id
         WHERE lp.id = NEW.lote_origen_id;
        SELECT productor_id INTO v_productor_compra FROM compra_feder WHERE id = NEW.compra_id;
        IF v_productor_lote IS NOT NULL AND v_productor_compra IS NOT NULL
           AND v_productor_lote <> v_productor_compra THEN
            PERFORM feder_rechazar('rg_detalle_compra_un_solo_productor', 'detalle_compra',
                'Todos los detalles de una compra corresponden a lotes de producciones de su propio productor.');
        END IF;
    ELSE
        IF NEW.compra_id IS DISTINCT FROM OLD.compra_id OR NEW.lote_origen_id IS DISTINCT FROM OLD.lote_origen_id THEN
            PERFORM feder_rechazar('rg_detalle_compra_origen_fijo', 'detalle_compra',
                'La compra y el lote de origen de un detalle se fijan al crearlo y nunca cambian.');
        END IF;
        IF NEW.precio_unitario IS DISTINCT FROM OLD.precio_unitario
           OR NEW.cantidad_recibida IS DISTINCT FROM OLD.cantidad_recibida
           OR NEW.cantidad_rechazada IS DISTINCT FROM OLD.cantidad_rechazada
           OR NEW.cantidad_cancelada IS DISTINCT FROM OLD.cantidad_cancelada THEN
            SELECT fecha_pago_productor INTO v_fecha_pago FROM compra_feder WHERE id = OLD.compra_id;
            IF NEW.precio_unitario IS DISTINCT FROM OLD.precio_unitario
               AND (v_fecha_pago IS NOT NULL
                    OR EXISTS (SELECT 1 FROM lote_feder WHERE detalle_compra_id = OLD.id)
                    OR EXISTS (SELECT 1 FROM bitacora b
                                WHERE b.entidad = 'DETALLE_COMPRA' AND b.entidad_id = OLD.id
                                  AND b.detalle ->> 'operacion' = 'RECEPCION'
                                  AND jsonb_typeof(b.detalle -> 'cantidad_aceptada') = 'number'
                                  AND (b.detalle ->> 'cantidad_aceptada')::numeric > 0)) THEN
                PERFORM feder_rechazar('rg_detalle_compra_precio_fijo', 'detalle_compra',
                    'El precio de adquisición no se modifica desde la primera aceptación de mercancía ni después del pago al productor.');
            END IF;
            IF v_fecha_pago IS NOT NULL
               AND (NEW.cantidad_recibida IS DISTINCT FROM OLD.cantidad_recibida
                    OR NEW.cantidad_rechazada IS DISTINCT FROM OLD.cantidad_rechazada
                    OR NEW.cantidad_cancelada IS DISTINCT FROM OLD.cantidad_cancelada) THEN
                PERFORM feder_rechazar('rg_detalle_compra_cantidades_fijas_tras_pago', 'detalle_compra',
                    'Después del pago al productor, las cantidades aceptadas, rechazadas y canceladas de la compra no cambian.');
            END IF;
        END IF;
    END IF;
    IF NEW.cantidad_comprada <> trunc(NEW.cantidad_comprada)
       OR NEW.cantidad_recibida <> trunc(NEW.cantidad_recibida)
       OR NEW.cantidad_rechazada <> trunc(NEW.cantidad_rechazada)
       OR NEW.cantidad_cancelada <> trunc(NEW.cantidad_cancelada) THEN
        v_producto_id := feder_producto_de_lote_produccion(NEW.lote_origen_id);
        PERFORM feder_exigir_cantidad_entera(v_producto_id, NEW.cantidad_comprada,
            'rg_detalle_compra_cantidad_entera', 'detalle_compra', 'cantidad_comprada');
        PERFORM feder_exigir_cantidad_entera(v_producto_id, NEW.cantidad_recibida,
            'rg_detalle_compra_cantidad_entera', 'detalle_compra', 'cantidad_recibida');
        PERFORM feder_exigir_cantidad_entera(v_producto_id, NEW.cantidad_rechazada,
            'rg_detalle_compra_cantidad_entera', 'detalle_compra', 'cantidad_rechazada');
        PERFORM feder_exigir_cantidad_entera(v_producto_id, NEW.cantidad_cancelada,
            'rg_detalle_compra_cantidad_entera', 'detalle_compra', 'cantidad_cancelada');
    END IF;
    RETURN NEW;
END;
$$;

