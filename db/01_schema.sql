-- =====================================================================================
-- FEDER · INF513 (UAGRM) · Sistema dirigido por correo electrónico
-- 01_schema.sql · Esquema PostgreSQL del modelo técnico aprobado (CU1–CU8)
--
-- Contenido:
--   1. Tablas del modelo UML (25 clases → 25 tablas; 40 asociaciones → 40 claves foráneas).
--   2. Índices de apoyo (claves foráneas, estados y fechas).
--   3. Funciones y disparadores que protegen invariantes (no implementan procesos de negocio).
--   4. Catálogo cerrado de roles (ROL «Catálogo cerrado»).
--   5. Infraestructura del procesador de correo (3 tablas técnicas, fuera del modelo UML).
--
-- Convenciones:
--   - Tabla = nombre de la clase en minúsculas. PK: id BIGINT GENERATED BY DEFAULT AS IDENTITY.
--   - Enumeraciones: VARCHAR + CHECK con los literales exactos del modelo.
--   - Nombres de restricciones: pk_<tabla>, fk_<tabla>_<rol>, uq_<tabla>_<columnas>, ck_<tabla>_<regla>,
--     ix_<tabla>_<columnas>, tg_<tabla>_<regla>. La capa Java traduce las violaciones por ese nombre.
--   - Las reglas protegidas por disparador se rechazan con SQLSTATE P0001, un mensaje en español y,
--     en el campo «constraint» del error, un identificador rg_<tabla>_<regla>.
--   - ON DELETE RESTRICT por defecto (se conserva el historial); CASCADE solo en datos sin valor
--     histórico (carrito y códigos de confirmación).
--
-- Requisitos: PostgreSQL 11 o posterior (columnas de identidad y EXECUTE FUNCTION). Probado en PostgreSQL 18.
-- Nota de versión: desde PostgreSQL 18, un borrado impedido por ON DELETE RESTRICT devuelve el SQLSTATE
-- 23001 (restrict_violation); en versiones anteriores devuelve 23503 (foreign_key_violation).
--
-- INSTALACIÓN NO DESTRUCTIVA: el script no elimina nada. Si la base ya contiene alguna de las 28 tablas
-- de FEDER, se detiene con un error antes de crear nada (la transacción se revierte y la base queda
-- intacta). Para reinstalar en el entorno LOCAL se recrea la base completa con
-- scripts/pg-local.ps1 reset-db; en la base institucional nunca se borran tablas ni datos.
-- Se ejecuta en una sola transacción: si algo falla, no queda nada aplicado.
-- =====================================================================================

SET client_encoding = 'UTF8';

BEGIN;

SET LOCAL search_path = public;
SET LOCAL client_min_messages = warning;

DO $$
DECLARE
    existentes TEXT;
BEGIN
    SELECT string_agg(c.relname, ', ' ORDER BY c.relname) INTO existentes
      FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = current_schema()
       AND c.relname IN (
           'confirmacion_operacion', 'correo_saliente', 'mensaje_correo',
           'reembolso', 'devolucion', 'notificacion', 'entrega', 'factura', 'pago', 'historial_pedido',
           'movimiento_inventario', 'reserva_stock', 'detalle_pedido', 'pedido', 'item_carrito',
           'lote_feder', 'detalle_compra', 'compra_feder', 'lote_produccion', 'produccion', 'productor',
           'producto', 'categoria', 'comunidad_agricola', 'bitacora', 'usuario_rol', 'usuario', 'rol');
    IF existentes IS NOT NULL THEN
        RAISE EXCEPTION 'La base % ya contiene objetos de FEDER (%); no se modificó nada.', current_database(), existentes
            USING HINT = 'Este script solo instala sobre una base sin esas tablas. En el entorno local, recree la base con scripts/pg-local.ps1 reset-db.';
    END IF;
END
$$;

