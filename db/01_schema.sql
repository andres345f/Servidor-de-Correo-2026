-- 3. FUNCIONES Y DISPARADORES DE PROTECCIÓN DE INVARIANTES
--
--    Solo protegen hechos que la base puede garantizar con fiabilidad: inmutabilidad de datos
--    fijados, coherencia entre filas cuyos datos comparados no cambian y las reglas para las que el
--    modelo indica expresamente un disparador. Los procesos (reserva de stock, máquinas de estados,
--    totales, límites por suma) son de la capa de negocio. Las comprobaciones entre filas suponen el
--    nivel de aislamiento READ COMMITTED que usa la aplicación.
