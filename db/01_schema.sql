    -- La inspección solo declara aptas unidades recibidas (evita que el CHECK anterior pase por nulos).
    CONSTRAINT ck_devolucion_apta_requiere_recibida CHECK (cantidad_apta IS NULL OR cantidad_recibida IS NOT NULL),
    CONSTRAINT ck_devolucion_importe_reembolsable CHECK (importe_reembolsable >= 0),
