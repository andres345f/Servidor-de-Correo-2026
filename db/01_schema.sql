    CONSTRAINT ck_movimiento_inventario_devolucion_segun_tipo CHECK (
        (tipo IN ('ENTRADA_DEVOLUCION', 'SALIDA_REPOSICION') AND devolucion_id IS NOT NULL)
        OR tipo = 'AJUSTE_NEGATIVO'
        OR (tipo IN ('ENTRADA_COMPRA', 'ANULACION_RECEPCION', 'SALIDA_VENTA', 'ENTRADA_RETORNO_ENTREGA',
                     'AJUSTE_POSITIVO', 'BAJA_VENCIDO', 'BAJA_DANADO', 'BAJA_DEFECTUOSO') AND devolucion_id IS NULL)),
    -- «Referencias según tipo»: la anulación de recepción, los ajustes y las bajas exigen motivo.
    CONSTRAINT ck_movimiento_inventario_motivo_segun_tipo CHECK (
        tipo NOT IN ('ANULACION_RECEPCION', 'AJUSTE_POSITIVO', 'AJUSTE_NEGATIVO',
                     'BAJA_VENCIDO', 'BAJA_DANADO', 'BAJA_DEFECTUOSO')
        OR (motivo IS NOT NULL AND btrim(motivo) <> ''))
