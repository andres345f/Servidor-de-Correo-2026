-- ---- REEMBOLSO «Mismo pedido y datos fijos», «Origen coherente» y «Límite por pago» (pago PAGADO)
CREATE OR REPLACE FUNCTION tgf_reembolso_integridad()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_estado_pago     varchar(15);
    v_pedido_pago     bigint;
    v_estado_pedido   varchar(30);
    v_resolucion      varchar(15);
    v_despacho        bigint;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.pago_id IS DISTINCT FROM OLD.pago_id
           OR NEW.devolucion_id IS DISTINCT FROM OLD.devolucion_id
           OR NEW.monto IS DISTINCT FROM OLD.monto
           OR NEW.clave_idempotencia IS DISTINCT FROM OLD.clave_idempotencia THEN
            PERFORM feder_rechazar('rg_reembolso_datos_fijos', 'reembolso',
                'El pago, la devolución, el monto y la clave de idempotencia de un reembolso no cambian tras crearse.');
        END IF;
        RETURN NEW;
    END IF;

    SELECT estado, pedido_id INTO v_estado_pago, v_pedido_pago FROM pago WHERE id = NEW.pago_id;
    IF NOT FOUND THEN
        RETURN NEW;  -- la clave foránea informará del pago inexistente
    END IF;
    IF v_estado_pago <> 'PAGADO' THEN
        PERFORM feder_rechazar('rg_reembolso_pago_pagado', 'reembolso',
            'Solo se reintegra dinero de un pago PAGADO.');
    END IF;
    IF NEW.devolucion_id IS NULL THEN
        SELECT estado INTO v_estado_pedido FROM pedido WHERE id = v_pedido_pago;
        IF v_estado_pedido <> 'CANCELADO' THEN
            PERFORM feder_rechazar('rg_reembolso_sin_devolucion_pedido_cancelado', 'reembolso',
                'Un reintegro sin devolución solo procede sobre un pedido CANCELADO.');
        END IF;
    ELSE
        SELECT resolucion, movimiento_inventario_id INTO v_resolucion, v_despacho
          FROM devolucion WHERE id = NEW.devolucion_id;
        IF FOUND THEN
            IF v_resolucion IS DISTINCT FROM 'REEMBOLSO' THEN
                PERFORM feder_rechazar('rg_reembolso_devolucion_con_reembolso', 'reembolso',
                    'Solo una devolución aprobada con resolución REEMBOLSO admite reintegros.');
            END IF;
            IF feder_pedido_de_movimiento(v_despacho) IS DISTINCT FROM v_pedido_pago THEN
                PERFORM feder_rechazar('rg_reembolso_mismo_pedido', 'reembolso',
                    'El pago reintegrado debe pertenecer al mismo pedido que la devolución.');
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_reembolso_integridad
    BEFORE INSERT OR UPDATE ON reembolso
    FOR EACH ROW EXECUTE FUNCTION tgf_reembolso_integridad();

