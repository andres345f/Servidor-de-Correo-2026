CREATE TABLE compra_feder (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    productor_id         BIGINT        NOT NULL,
    codigo               VARCHAR(30)   NOT NULL,
    fecha_compra         TIMESTAMPTZ   NOT NULL,
    estado               VARCHAR(20)   NOT NULL,
    total                NUMERIC(14,2) NOT NULL,
    fecha_pago_productor TIMESTAMPTZ,
    observacion          TEXT,
    CONSTRAINT pk_compra_feder PRIMARY KEY (id),
    CONSTRAINT fk_compra_feder_productor FOREIGN KEY (productor_id) REFERENCES productor (id) ON DELETE RESTRICT,
    CONSTRAINT uq_compra_feder_codigo UNIQUE (codigo),
    CONSTRAINT ck_compra_feder_estado CHECK (estado IN ('REGISTRADA', 'RECIBIDA_PARCIAL', 'RECIBIDA', 'CANCELADA')),
    CONSTRAINT ck_compra_feder_total CHECK (total >= 0),
    -- «Pago al productor»: el pago solo se registra con la compra RECIBIDA.
    CONSTRAINT ck_compra_feder_pago_solo_recibida CHECK (fecha_pago_productor IS NULL OR estado = 'RECIBIDA')
);
COMMENT ON TABLE compra_feder IS 'Adquisición de FEDER a un productor: productos terminados, sin factura.';

CREATE TABLE detalle_compra (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    compra_id          BIGINT        NOT NULL,
    lote_origen_id     BIGINT        NOT NULL,
    cantidad_comprada  NUMERIC(12,3) NOT NULL,
    precio_unitario    NUMERIC(12,2) NOT NULL,
    cantidad_recibida  NUMERIC(12,3) NOT NULL DEFAULT 0,
    cantidad_rechazada NUMERIC(12,3) NOT NULL DEFAULT 0,
    cantidad_cancelada NUMERIC(12,3) NOT NULL DEFAULT 0,
    CONSTRAINT pk_detalle_compra PRIMARY KEY (id),
    CONSTRAINT fk_detalle_compra_compra FOREIGN KEY (compra_id) REFERENCES compra_feder (id) ON DELETE RESTRICT,
    CONSTRAINT fk_detalle_compra_lote_origen FOREIGN KEY (lote_origen_id) REFERENCES lote_produccion (id) ON DELETE RESTRICT,
    -- «Lote único por compra».
    CONSTRAINT uq_detalle_compra_compra_lote_origen UNIQUE (compra_id, lote_origen_id),
    CONSTRAINT ck_detalle_compra_cantidad_comprada CHECK (cantidad_comprada > 0),
    CONSTRAINT ck_detalle_compra_precio_unitario CHECK (precio_unitario >= 0),
    CONSTRAINT ck_detalle_compra_cantidad_recibida CHECK (cantidad_recibida >= 0),
    CONSTRAINT ck_detalle_compra_cantidad_rechazada CHECK (cantidad_rechazada >= 0),
    CONSTRAINT ck_detalle_compra_cantidad_cancelada CHECK (cantidad_cancelada >= 0),
    -- «Recepción, rechazo y cancelación»: lo resuelto nunca supera lo acordado (pendiente >= 0).
    CONSTRAINT ck_detalle_compra_cantidades_resueltas CHECK (
        cantidad_recibida + cantidad_rechazada + cantidad_cancelada <= cantidad_comprada)
);
COMMENT ON TABLE detalle_compra IS 'Línea de una compra: cantidad acordada de un lote de origen y cómo se resolvió.';

CREATE TABLE lote_feder (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    detalle_compra_id   BIGINT        NOT NULL,
    codigo              VARCHAR(30)   NOT NULL,
    fecha_ingreso       TIMESTAMPTZ   NOT NULL,
    cantidad_disponible NUMERIC(12,3) NOT NULL,
    cantidad_reservada  NUMERIC(12,3) NOT NULL DEFAULT 0,
    ubicacion_almacen   VARCHAR(60),
    estado              VARCHAR(20)   NOT NULL,
    CONSTRAINT pk_lote_feder PRIMARY KEY (id),
